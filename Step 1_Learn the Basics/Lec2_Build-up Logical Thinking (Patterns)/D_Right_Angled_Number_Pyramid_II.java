public class D_Right_Angled_Number_Pyramid_II {
    public static void main(String[] args) {
        for(int i=1;i<=5;i++)
            {
                for(int j=0;j<i;j++)
                    {
                        System.out.print(i+" ");
                    }
                    System.out.println();
            }
    }
}
