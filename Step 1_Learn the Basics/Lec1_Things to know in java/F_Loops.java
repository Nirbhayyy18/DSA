public class F_Loops {
    public static void main(String[] args) {
        
        // For Loop
        for(int i=1;i<=10;i++)
            {
                System.out.println(i);
            }

        // While Loop
        int a=0;
        while(a++<10)
            {
                System.out.println(a);
            }
    }
}
